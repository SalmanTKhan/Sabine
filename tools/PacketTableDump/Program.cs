using System;
using System.IO;
using System.Linq;
using System.Text;
using Sabine.Shared;
using Sabine.Shared.Network;

namespace Sabine.Tools.PacketTableDump
{
	// One-shot dumper. Resolves the Sabine-native (v50000) packet table at
	// runtime by setting Game.Version = Versions.Sabine and calling
	// PacketTable.Load(), then writes a markdown reference doc next to the
	// other packet_table_NNNN.md files. The OpenMidgard client consumes the
	// markdown through the Ref/Sabine symlink when populating PV50000.
	//
	// Run: dotnet run --project tools/PacketTableDump -- [outDir]
	//   outDir defaults to docs/network/packet_tables/ relative to the
	//   repository root (auto-detected by walking up from the binary).
	internal static class Program
	{
		private static int Main(string[] args)
		{
			Game.Version = Versions.Sabine;
			PacketTable.Load();

			var version = Versions.Sabine;
			var outDir = args.Length > 0 ? args[0] : DefaultOutputDir();
			Directory.CreateDirectory(outDir);

			var entries = PacketTable.GetTable()
				.OrderBy(e => e.OpNetwork)
				.ToList();

			var sb = new StringBuilder();
			sb.AppendLine($"Protocol Version {version}");
			sb.AppendLine(new string('=', 78));
			sb.AppendLine();
			sb.AppendLine("Sabine-native protocol. Generated by src/PacketTableDump from");
			sb.AppendLine("PacketTable.Sabine.cs after stacking every historical era table");
			sb.AppendLine("(100..2500), applying the rA-modern ChangeSize upgrades, and");
			sb.AppendLine("renumbering by Op enum-ordinal into grouped wire-ID blocks:");
			sb.AppendLine();
			sb.AppendLine("  0x0001-0x00FF  Auth (CA_* / AC_*)");
			sb.AppendLine("  0x0100-0x01FF  Char (CH_* / HC_*)");
			sb.AppendLine("  0x0200-0x03FF  Zone client to server (CZ_*)");
			sb.AppendLine("  0x0400-0x0FFF  Zone server to client (ZC_*)");
			sb.AppendLine("  0x4000+        Misc (PING, SC_*, etc.)");
			sb.AppendLine();
			sb.AppendLine("Re-run after any change to PacketTable.Sabine.cs or Op.cs.");
			sb.AppendLine();
			sb.AppendLine("Name                                       | Op       | Size");
			sb.AppendLine("-------------------------------------------|----------|-------");

			foreach (var entry in entries)
			{
				var name = entry.Op.ToString();
				var hex = $"0x{entry.OpNetwork:X4}";
				var size = entry.Size == PacketTable.Dynamic ? "-1" : entry.Size.ToString();
				sb.AppendLine($"{name,-42} | {hex,-8} | {size}");
			}

			var path = Path.Combine(outDir, $"packet_table_{version}.md");
			File.WriteAllText(path, sb.ToString());

			// Also emit a C++ snippet for direct paste into OpenMidgard's
			// PopulatePv50000. Saves transcribing 600+ entries by hand and
			// keeps the table mechanically refreshable.
			var cpp = new StringBuilder();
			cpp.AppendLine("// Generated by Sabine.Tools.PacketTableDump from PacketTable.Sabine.cs.");
			cpp.AppendLine("// Do not edit by hand — re-run `dotnet run --project src/PacketTableDump`");
			cpp.AppendLine("// in the Sabine repo and vendor the refreshed file.");
			cpp.AppendLine("//");
			cpp.AppendLine($"// Protocol version: {version}  Entries: {entries.Count}");
			cpp.AppendLine();
			foreach (var entry in entries)
			{
				var name = entry.Op.ToString();
				var size = entry.Size == PacketTable.Dynamic ? "kVariablePacketSize" : entry.Size.ToString();
				cpp.AppendLine($"    Set(t, 0x{entry.OpNetwork:X4}, {size}); // {name}");
			}
			var cppPath = Path.Combine(outDir, $"packet_table_{version}.inc");
			File.WriteAllText(cppPath, cpp.ToString());

			// And a C++ header of named constants mirroring Op.cs. Lets
			// OpenMidgard reference Sabine ops by name (OpV50000::CA_LOGIN)
			// instead of bare hex, so cross-referencing against Sabine
			// PacketTable / PacketHandler code is mechanical.
			var hdr = new StringBuilder();
			hdr.AppendLine("#pragma once");
			hdr.AppendLine("//");
			hdr.AppendLine("// Generated by Sabine.Tools.PacketTableDump from PacketTable.Sabine.cs.");
			hdr.AppendLine("// Do not edit by hand — re-run `dotnet run --project src/PacketTableDump`");
			hdr.AppendLine("// in the Sabine repo and vendor the refreshed file.");
			hdr.AppendLine("//");
			hdr.AppendLine($"// Protocol version: {version}  Entries: {entries.Count}");
			hdr.AppendLine("//");
			hdr.AppendLine("// Names mirror Sabine's Op.cs enum exactly. Wire IDs are produced by");
			hdr.AppendLine("// LoadVersionSabine's enum-ordinal renumber pass (auth 0x0001+, char");
			hdr.AppendLine("// 0x0100+, CZ 0x0200+, ZC 0x0400+, misc 0x4000+).");
			hdr.AppendLine();
			hdr.AppendLine("#include \"Types.h\"");
			hdr.AppendLine();
			hdr.AppendLine("namespace ro::net::OpV50000 {");
			foreach (var entry in entries)
			{
				var name = entry.Op.ToString();
				hdr.AppendLine($"constexpr u16 {name} = 0x{entry.OpNetwork:X4};");
			}
			hdr.AppendLine("} // namespace ro::net::OpV50000");
			var hdrPath = Path.Combine(outDir, $"OpV{version}.generated.h");
			File.WriteAllText(hdrPath, hdr.ToString());

			Console.WriteLine($"Wrote {entries.Count} entries to {path}");
			Console.WriteLine($"Wrote C++ snippet to {cppPath}");
			Console.WriteLine($"Wrote C++ header to {hdrPath}");
			return 0;
		}

		private static string DefaultOutputDir()
		{
			// Walk up from the binary until we find the repo root
			// (recognized by Sabine.sln), then point at the docs tree.
			var dir = AppContext.BaseDirectory;
			for (var i = 0; i < 8 && dir != null; i++)
			{
				if (File.Exists(Path.Combine(dir, "Sabine.sln")))
					return Path.Combine(dir, "docs", "network", "packet_tables");
				dir = Path.GetDirectoryName(dir);
			}
			return Path.Combine(Environment.CurrentDirectory, "docs", "network", "packet_tables");
		}
	}
}
